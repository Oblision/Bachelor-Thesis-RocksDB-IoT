#!/usr/bin/env bash
# Control experiments at rho~1 (run AFTER matrix.sh so they don't perturb its perf numbers):
#  1. BURST: bursty arrival/cardinality vs the smooth rho1 -> RQ2 tail-latency under bursts.
#  2. TMPFS-SPILL: OOC spilling to RAM (tmpfs) instead of SD -> isolates spill COMPUTE cost from SD I/O cost (RQ3/RQ4).
#  3. DEPTH (optional): one hot window > cap -> OOC OOMs (confirms OOC rescues breadth, not depth).
set -u
cd "$(dirname "${BASH_SOURCE[0]}")"
export SYSTEST=cmake-build-release/nes-systests/systest/systest
export TEMPLATE=genfile.test EMITBPS=0
W=50000; L=2000000; POOL=14000; CPUSET=0,1,8,9; WTH=2
COMMON="$W 0 $L"
run(){ DCPUS=2 ./run-cell.sh "$@" "$CPUSET" $WTH "" "" 16 8 4; }

# 1. BURST (needs /dev/shm/nes-input/rho1_burst.csv, generated by the caller)
if [ -s /dev/shm/nes-input/rho1_burst.csv ]; then
  export FILECSV=/dev/shm/nes-input/rho1_burst.csv
  for r in 1 2 3; do run burst_uncap_r$r 55000000 $COMMON none on off 100000 100000 $POOL; done
  for r in 1 2 3; do run burst_ooc_r$r   55000000 $COMMON 512  on off 50    100    $POOL; done
fi

# 2. TMPFS-SPILL: same workload as rho1 OOC but spill to RAM (isolate compute vs SD I/O)
export FILECSV=/dev/shm/nes-input/cal_rho.csv
mkdir -p /dev/shm/nes-spill
for r in 1 2 3; do SPILL_HOST_DIR=/dev/shm/nes-spill run tmpfsspill_ooc_r$r 55000000 $COMMON 512 on off 50 100 $POOL; done

echo "==== CONTROLS SUMMARY ===="
printf '%-22s %-4s %-4s %6s %4s %10s %6s %12s\n' label rc st peakMB slc tps p99us io_w
for f in results/burst_*.tsv results/tmpfsspill_*.tsv; do
  [ -s "$f" ] && awk -F'\t' '{printf "%-22s %-4s %-4s %6s %4s %10s %6s %12s\n",$1,$9,$10,$12,$15,$22,$21,$18}' "$f"
done 2>/dev/null
